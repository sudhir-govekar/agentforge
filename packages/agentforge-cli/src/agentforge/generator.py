def to_package_name(project_name: str) -> str:

    """Convert a project name into a valid Python package name."""

    package_name = re.sub(r"[^a-zA-Z0-9]+", "_", project_name)

    package_name = package_name.strip("_").lower()

    if not package_name:

        raise ValueError("Project name must contain letters or numbers.")

    if package_name[0].isdigit():

        package_name = f"app_{package_name}"

    return package_name

def validate_project_name(project_name: str) -> None:

    """Validate the project directory name."""

    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", project_name):

        raise ValueError(

            "Project name must start with a letter or number and contain "

            "only letters, numbers, hyphens, and underscores."

        )

